function cm=cmaps(n)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%%%%%%%%%% Colormaps
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
cm=zeros(256,3);
r1=zeros(256,1);
g1=zeros(256,1);
b1=zeros(256,1);

i=1:99;
    r1(i)=i/100;
    b1(i)=1;
    g1(i)=i/100;
    clear i
i=100:155;
    r1(i)=1;
    b1(i)=1;
    g1(i)=1; 
clear i
i=156:256;
    r1(i)=1;
    b1(i)=(256-i)/100;
    g1(i)=(256-i)/100;
clear i

cm=[r1 g1 b1];
end