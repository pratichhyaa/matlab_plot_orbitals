function YLM=Ylm_Reg(ps,llim,x,y,z,r)
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%%%%%                                                                 %%%%%
%%%%%               Program to Generate Cubic Harmonics               %%%%%
%%%%%       Real, Cartesian representation Spherical Harmonics        %%%%%
%%%%%         Cubic Harmonics are output on Cartesian grids           %%%%%
%%%%%                                                                 %%%%%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%%%%%                                                                 %%%%%
%%%%%              Last Modified:    March 26 2024  
%%%%%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
clearvars Ph YLM
P={     0,    0,    0,    0, @P00,    0,    0,    0,    0; 
        0,    0,    0, @P11, @P11, @P10,    0,    0,    0;
        0,    0, @P20, @P21, @P21, @P22, @P22,    0,    0;
        0, @P30, @P31, @P31, @P32, @P32, @P33, @P33,    0;
     @P40, @P41, @P41, @P42, @P42, @P43, @P43, @P44, @P44}; 
A={     0,    0,    0,    0,  @A0,    0,    0,    0,    0;
        0,    0,    0,  @A1,  @B1,  @A0,    0,    0,    0;
        0,    0,  @A0,  @A1,  @B1,  @A2,  @B2,    0,    0;
        0,  @A0,  @A1,  @B1,  @A2,  @B2,  @A3,  @B3,    0;
      @A0,  @B1,  @A1,  @B2,  @A2,  @B3,  @A3,  @B4,  @A4};
% P={     0,    0,    0,    0, @P00,    0,    0,    0,    0; 
%         0,    0,    0, @P11, @P10, @P11,    0,    0,    0;
%         0,    0, @P22, @P21, @P20, @P21, @P22,    0,    0;
%         0, @P33, @P32, @P31, @P30, @P31, @P32, @P33,    0;
%      @P40, @P41, @P41, @P42, @P42, @P43, @P43, @P44, @P44}; 
% A={     0,    0,    0,    0,  @A0,    0,    0,    0,    0;
%         0,    0,    0,  @B1,  @A0,  @A1,    0,    0,    0;
%         0,    0,  @B2,  @B1,  @A0,  @A1,  @A2,    0,    0;
%         0,  @B3,  @B2,  @B1,  @A0,  @A1,  @A2,  @A3,    0;
%       @A0,  @B1,  @A1,  @B2,  @A2,  @B3,  @A3,  @B4,  @A4};  
lcen=5;
clearvars YLM
YLM(ps+1,ps+1,ps+1,llim+1,2*llim+1)=zeros;
cen=ps/2+1;                                                    %grid center
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%%%%%                                                                 %%%%%
%%%%%   Solid Harmonics indexed as l,m where the l index is l + 1     %%%%%
%%%%%   and the m index is m+lmax+1                                   %%%%%
%%%%%                                                                 %%%%%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
for l=0:llim
    for m=-l:l     
        %(sqrt(4*pi/(2*l+1))).*(r.^l).*(sqrt((2*l+1)/4/pi)).*
        YLM(:,:,:,l+1,m+llim+1)=(sqrt((2*l+1)/4/pi)).*(r.^(-l)).*P{l+1,lcen+m}(z,r).*A{l+1,lcen+m}(x,y);    
        if ne(l,0)
        YLM(cen,cen,cen,l+1,m+llim+1)=0;
        end
        
    end
end
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
function Am0=A0(~,~)
        Am0=1;
end
function Am1=A1(x,~)
        Am1=x;
end

function Am2=A2(x,y)
        Am2=x.^2-y.^2;
end


function Am3=A3(x,y)
        Am3=x.^3-3*x.*(y.^2);
end
function Am4=A4(x,y)
        Am4=x.^4-6*(x.^2).*(y.^2)+y.^4;
end
function Bm0=B0(~,~)
        Bm0=0;
end
function Bm1=B1(~,y)
        Bm1=y;
end
function Bm2=B2(x,y)
        Bm2=2*x.*y;
 end

function Bm3=B3(x,y)
        Bm3=3*(x.^2).*y-y.^3;
end
function Bm4=B4(x,y)
        Bm4=4*(x.^3).*y-4*x.*(y.^3);
end

function p00=P00(~,~)
p00=1;
end

function p11=P11(~,~)
         p11=1;
end
function p10=P10(z,~)
   p10=z;
end

 function p22=P22(~,~)
    p22=sqrt(3)/2;
 end
 
 function p21=P21(z,~)
    p21=sqrt(3)*z;
 end
 
 function p20=P20(z,r)       
    p20=0.5*(3*(z.^2)-r.^2);
 end

function p33=P33(~,~)
    p33=1/4*sqrt(10);
end

function p32=P32(z,~)
    p32=(1/2)*sqrt(15)*z;
end

function p31=P31(z,r)
    p31=(1/4)*sqrt(6)*(5*z.^2-r.^2);
end

function p30=P30(z,r)
 p30=0.5*(5*z.^3-3*z.*(r.^2));   
end

function p44=P44(~,~)
    p44=1/8*sqrt(35);
end

function p43=P43(z,~)
    p43=1/4*sqrt(70)*z;
end

function p42=P42(z,r)
    p42=1/4*sqrt(5)*(7*z.^2-r.^2);
end

function p41=P41(z,r)
    p41=sqrt(10)/4*(7*z.^3-3*z.*r.^2);
end

function p40=P40(z,r)
    p40=1/8*(35*z.^4-30*(z.^2).*(r.^2)+3*r.^4);   
end


end
